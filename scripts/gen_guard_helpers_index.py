#!/usr/bin/env python3
"""Generate the grouped helper index inside ``agentsec/guards/base.py``'s module docstring.

``base.py`` is the shared toolbox every guard is told to reach for, and it is far too long to
browse. Three documents (``CLAUDE.md``, ``CONTRIBUTING-GUARDS.md``, the guard-factory skill) told a
guard author "reuse the shared helpers" and then named five of them; the rest were undiscoverable,
including the comment strippers and the cross-file router-auth resolvers that a new guard is most
likely to re-roll badly (codebase-as-prompt audit 2026-08-27, QW3).

So the index is generated rather than written, for the same reason ``wiki/guards/index.md`` is: a
hand-maintained inventory of this size rots within a week. Two properties make it stay honest:

1. **The description IS the helper's own docstring.** Nothing to keep in sync with anything, because
   the source of truth is a few hundred lines further down the same file.
2. **Every public helper must be grouped and documented, or this script fails.** A missing group is
   an error naming the function, never a silent "Other" bucket -- that is the ``findings.py::_AREA``
   failure mode BB4 spent a migration removing (a default bucket degrades quietly, and nothing says
   so). ``tests/test_guard_helpers_index.py`` is the CI gate.

Grouping is declared in place, next to the code, the same way a guard declares its own ``area``:
a helper belongs to the nearest ``# === helpers: <Group> ===`` banner above it. Repeated banner
titles merge into one section in the rendered index, so a helper that sits out of cluster is handled
by re-opening its group with a second banner rather than by MOVING it. Moving is not a safe
refactor here: ``base.py`` computes module-level constants from module-level functions
(``AUTH_DEPENDS_SIGNAL`` calls ``boundaried_stems``), so definition order is load-bearing.

Usage::

    python scripts/gen_guard_helpers_index.py --write     # regenerate the index in base.py
    python scripts/gen_guard_helpers_index.py --check     # exit 1 if it is out of sync
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "agentsec" / "guards" / "base.py"

BEGIN = "--- helper index: generated by scripts/gen_guard_helpers_index.py, do not edit by hand ---"
END = "--- end helper index ---"

# `# === helpers: <Group> ===...`. Deliberately `===`, so it cannot be confused with the four
# ordinary `# --- ... ---` section comments base.py already carries.
_BANNER = re.compile(r"^# === helpers: (.+?) =+$")

# One line per helper, inside base.py's 110-column budget: 2 indent + 32 name column + 1 + summary.
#
# The name is written BARE, without a trailing `()`. That is load-bearing, not a style choice: this
# index lives inside a file under `agentsec/guards/`, and
# `tests/test_guard_sandbox.py::test_is_nonproduct_path_callers_thread_archive_segments` text-scans
# every line of every guard module for `is_nonproduct_path(` to prove each call site threads
# `archive_segments`. An index row reading `is_nonproduct_path()` is indistinguishable from a call
# site to that scan, and it failed on exactly that. Fixing the index was the right half to change:
# teaching the sandbox gate to skip a region would have been a narrowing of a live security gate to
# accommodate a cosmetic choice here. Do not "restore" the parens.
_NAME_COL = 32
_INDENT = "  "
MAX_SUMMARY = 75


class GeneratorError(Exception):
    """The source cannot be indexed as-is, and the fix is a source edit, not a re-run."""


class Helper(NamedTuple):
    group: str
    name: str
    summary: str


def split_lines(source: str) -> list[str]:
    """Source split the way ``ast`` counts lines: on ``\\n`` only.

    NOT ``str.splitlines()``, which also splits on U+2028/U+2029, ``\\x0b``, ``\\x0c`` and ``\\x85``.
    ``base.py`` contains literal U+2028 and U+2029 inside its JS line-terminator constants
    (``_JS_LINE_BOUNDARIES`` and friends), so ``splitlines()`` reports six more lines than the
    tokenizer does and every ``lineno``-based splice below would land in the wrong place.
    """
    return source.split("\n")


def summary(docstring: str) -> str:
    """A helper's leading docstring paragraph, whitespace-collapsed and length-capped.

    The leading PARAGRAPH, not the first physical line and not the first sentence. Most helpers in
    ``base.py`` wrap their opening sentence across physical lines, so a first-line rule yields
    fragments; and sentence-splitting on ``.`` truncates mid-token on the ones whose summary
    contains ``{ ... }`` (see ``iter_terraform_locals_blocks``). Over-long paragraphs are cut at a
    word boundary and marked with an ellipsis: this index exists so you can find the right helper,
    and its docstring is right there once you have.
    """
    paragraph: list[str] = []
    for line in docstring.strip().split("\n"):
        if not line.strip():
            break
        paragraph.append(line.strip())
    text = " ".join(" ".join(paragraph).split())
    if len(text) <= MAX_SUMMARY:
        return text
    cut = text[: MAX_SUMMARY - 3]
    if " " in cut:
        cut = cut[: cut.rindex(" ")]
    # `.` is in the strip set so a cut landing just past a sentence end reads "layout..." and
    # not "layout....".
    return cut.rstrip(" ,;:-.") + "..."


def helpers(source: str) -> list[Helper]:
    """Every public module-level function in ``source``, in file order, with its group.

    Raises ``GeneratorError`` naming the offender if a helper has no banner above it or no
    docstring. Both are source bugs a guard author must fix, not conditions to render around.
    """
    lines = split_lines(source)
    banners = [
        (number, match.group(1).strip())
        for number, line in enumerate(lines, start=1)
        if (match := _BANNER.match(line))
    ]

    out: list[Helper] = []
    for node in ast.parse(source).body:
        # `ast.AsyncFunctionDef` is a separate node type, not a subclass. Filtering on
        # `ast.FunctionDef` alone dropped an `async def` helper from the index silently, with no
        # error - the one outcome this function is written never to produce (#748 review).
        if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) or node.name.startswith("_"):
            continue
        start = min([node.lineno, *(d.lineno for d in node.decorator_list)])
        above = [group for number, group in banners if number < start]
        if not above:
            raise GeneratorError(
                f"{node.name}() at line {start} has no `# === helpers: <Group> ===` banner above "
                "it. Add one (or move the helper below an existing banner) so it is grouped in the "
                "index; there is deliberately no catch-all bucket."
            )
        doc = ast.get_docstring(node)
        if not doc or not doc.strip():
            raise GeneratorError(
                f"{node.name}() at line {start} has no docstring, so the index has nothing to say "
                "about it. Give it a one-line summary describing what a guard would call it for."
            )
        out.append(Helper(above[-1], node.name, summary(doc)))
    return out


def render_index(source: str) -> list[str]:
    """The index block, WITHOUT the sentinel lines, as docstring lines."""
    found = helpers(source)
    if not found:
        # A sweep that silently collects nothing renders an empty index and reads as "no helpers
        # here" (CLAUDE.md review rule 3, a failure that presents as success).
        raise GeneratorError(f"no public helpers found in {BASE.name}; the parse collected nothing")

    order: list[str] = []
    for helper in found:
        if helper.group not in order:
            order.append(helper.group)

    lines: list[str] = []
    for group in order:
        if lines:
            lines.append("")
        lines.append(group)
        for helper in found:
            if helper.group == group:
                lines.append(f"{_INDENT}{helper.name:<{_NAME_COL}} {helper.summary}".rstrip())
    return lines


def render(source: str) -> str:
    """``source`` with the index region of its module docstring rebuilt. Idempotent."""
    lines = split_lines(source)
    tree = ast.parse(source)
    if not tree.body or not isinstance(tree.body[0], ast.Expr):
        raise GeneratorError(f"{BASE.name} has no module docstring to write the index into")
    node = tree.body[0]
    if not isinstance(node.value, ast.Constant) or not isinstance(node.value.value, str):
        raise GeneratorError(f"{BASE.name} has no module docstring to write the index into")

    literal = "\n".join(lines[node.lineno - 1 : node.end_lineno])
    match = re.fullmatch(r'(?P<prefix>[rR]?)(?P<quote>"""|\'\'\')(?P<body>.*)(?P=quote)', literal, re.DOTALL)
    if match is None:
        raise GeneratorError(f"{BASE.name}'s module docstring is not a plain triple-quoted literal")

    body = split_lines(match.group("body"))
    if BEGIN in body and END in body:
        head, tail = body[: body.index(BEGIN)], body[body.index(END) + 1 :]
    elif BEGIN in body or END in body:
        raise GeneratorError(f"{BASE.name}'s docstring has only one of the two index sentinels")
    else:
        head, tail = [*body, ""], [""]
    while head and head[-1].strip() == "":
        head.pop()
    while tail and tail[0].strip() == "":
        tail.pop(0)

    new_body = [*head, "", BEGIN, "", *render_index(source), "", END, "", *tail]
    if new_body[-1].strip() != "":
        new_body.append("")

    text = "\n".join(new_body)
    # A raw literal, always: `join_dockerfile_continuations`'s summary carries a literal backslash,
    # and in a NON-raw docstring `\`` is an invalid escape sequence -- ruff W605 (selected in
    # pyproject.toml) plus a CPython SyntaxWarning. The two conditions a raw triple-quoted string
    # still cannot express are checked rather than assumed.
    if '"""' in text:
        raise GeneratorError("the rendered docstring contains a triple quote and cannot be embedded")
    if text.endswith("\\"):
        raise GeneratorError("the rendered docstring ends with a backslash, which a raw string cannot")

    return "\n".join([*lines[: node.lineno - 1], f'r"""{text}"""', *lines[node.end_lineno :]])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the index (default)")
    group.add_argument("--check", action="store_true", help="exit 1 if the committed index is stale")
    args = parser.parse_args(argv)

    source = BASE.read_text(encoding="utf-8")
    try:
        expected = render(source)
    except GeneratorError as exc:
        print(f"agentsec/guards/base.py cannot be indexed: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if expected != source:
            print(
                "agentsec/guards/base.py's helper index is out of sync with its helpers. "
                "Run: python scripts/gen_guard_helpers_index.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"agentsec/guards/base.py helper index is in sync ({len(helpers(source))} helpers)")
        return 0

    # newline="" so the emitted "\n" endings are not re-translated to CRLF on Windows.
    with BASE.open("w", encoding="utf-8", newline="") as handle:
        handle.write(expected)
    print(f"wrote the helper index into {BASE.relative_to(ROOT).as_posix()} ({len(helpers(expected))} helpers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
