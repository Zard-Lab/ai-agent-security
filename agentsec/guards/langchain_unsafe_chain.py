"""Guard: LangChain chain types that execute model output without sandboxing (OWASP-LLM:LLM02/LLM05).

When an LLM's response is directly executed as code or shell commands, any successful
prompt injection attack becomes arbitrary code execution. LangChain's `langchain_experimental`
package ships several chain types that do exactly this — they are placed in the experimental
namespace precisely because they are dangerous.

Two statically detectable patterns:

  1. **`dangerous-chain-imported`** (HIGH): A chain class that executes model output directly
     is imported. Covered classes:
     - `LLMBashChain` — passes model output to the local shell via `subprocess`
     - `PALChain` (Program-Aided Language model) — executes Python generated by the model
     - `LLMMathChain` — evaluates mathematical expressions via Python `eval`
     These classes offer no sandboxing, no output-schema validation, and no execution timeout.
     Once the model has been successfully injected, the attacker has the same access as the
     process user.

  2. **`allow-dangerous-code`** (HIGH): `allow_dangerous_code=True` is set anywhere in the
     codebase. Newer LangChain versions require this flag explicitly when using the dangerous
     chains above — the library is asking the developer to opt in knowingly. Detecting the flag
     is equivalent to detecting that the developer has acknowledged and accepted the risk.

**Why HIGH?** Both patterns enable prompt-injection-to-RCE. The attack path is:
  LLM prompt injection → model generates malicious code → chain executes it → RCE.

**Relationship to other guards:**
  * `agent-tool-overpermission`: fires when the NEW tool API (pydantic-ai `@agent.tool`,
    LangChain `ShellTool`/`PythonREPLTool`) is used. This guard fires on the LEGACY chain API
    (`LLMBashChain`, `PALChain`) — a different surface, complementary coverage.
  * `llm-output-to-sink`: fires when model output is piped directly to exec or eval —
    the direct wrapping pattern. This guard fires on chain-level abstraction where
    the execution is internal to LangChain.
  * `command-injection`: fires on subprocess with dynamic args via HTTP; this fires on the
    model-as-input-source angle — the injection payload reaches the shell via the LLM.

**Checklist items:**
  * `4-langchain-unsafe-chains` — covered (both checks together give full static coverage)
  * `4-codeexec-sandboxed` — partial (detects the LangChain chain path; the tool path is
    covered by `agent-tool-overpermission/dangerous-tool-imported`)

**Suppress:** `# security: allow-langchain-unsafe-chain` in any file silences both checks
repo-wide. Use only when the chain is running inside a fully isolated sandbox (e.g. a
Docker container with no filesystem or network access, separate from the main service).
"""
from __future__ import annotations

import re
from pathlib import Path

from agentsec.detect import StackProfile
from agentsec.findings import Finding

from .base import CanaryPlant, Guard, iter_files, pragma_present, python_scan_dirs, read, rel

_PRAGMA = "security: allow-langchain-unsafe-chain"

_STANDARDS = ["OWASP-LLM:LLM02", "OWASP-LLM:LLM05"]

# LangChain chain classes that execute model output directly.
# All three live in langchain_experimental (or the legacy langchain.chains) precisely
# because they are unsafe by design.
_DANGEROUS_CHAIN_IMPORT = re.compile(
    r"\bfrom\s+langchain[\w.]*\s+import\b[^;\n]*"
    r"\b(?:LLMBashChain|PALChain|LLMMathChain)\b",
    re.IGNORECASE,
)

# The explicit opt-in flag that newer LangChain versions require for dangerous chains.
# Presence means the developer has acknowledged the risk; we surface it for reviewer attention.
_ALLOW_DANGEROUS_CODE = re.compile(
    r"\ballow_dangerous_code\s*=\s*True\b",
    re.IGNORECASE,
)


class LangchainUnsafeChainGuard(Guard):
    id = "langchain-unsafe-chain"
    title = "LangChain chain executes model output without sandboxing"
    area = "AI agent"

    # langchain_chains.py has two langchain-unsafe-chain plants:
    #   1. from langchain_experimental.llm_bash import LLMBashChain -> dangerous-chain-imported
    #   2. allow_dangerous_code=True -> allow-dangerous-code
    # Must NOT contain: allow-langchain-unsafe-chain pragma — it silences both checks repo-wide.
    canary_plant = CanaryPlant(
        files={
            "langchain_chains.py": (
                "from langchain_experimental.llm_bash import LLMBashChain\n"
                "from langchain_openai import ChatOpenAI\n"
                "\n"
                "llm = ChatOpenAI(model='gpt-4o')\n"
                "chain = LLMBashChain.from_llm(llm, allow_dangerous_code=True)\n"
                "\n"
                "\n"
                "def run_bash_chain(question: str) -> str:\n"
                "    return chain.invoke({'question': question})['output']\n"
            ),
        },
        expects=frozenset({
            "langchain-unsafe-chain/allow-dangerous-code",
            "langchain-unsafe-chain/dangerous-chain-imported",
        }),
    )

    def applies(self, profile: StackProfile) -> bool:
        return "llm" in profile.features

    def run(self, root: Path, profile: StackProfile) -> list[Finding]:
        files: list[tuple[Path, str]] = []
        seen: set[Path] = set()
        for d in python_scan_dirs(root, profile):
            for f in iter_files(d, (".py",)):
                if f in seen:
                    continue
                seen.add(f)
                files.append((f, read(f)))

        for _f, text in files:
            if pragma_present(_PRAGMA, text, dialect="python"):
                return []

        out: list[Finding] = []
        out += self._check_dangerous_chain(root, files)
        out += self._check_allow_dangerous_code(root, files)
        return out

    def _check_dangerous_chain(
        self, root: Path, files: list[tuple[Path, str]]
    ) -> list[Finding]:
        for f, text in files:
            for lineno, line in enumerate(text.splitlines(), 1):
                if _DANGEROUS_CHAIN_IMPORT.search(line):
                    return [Finding(
                        check_id=self.id,
                        severity="high",
                        title="Dangerous LangChain chain class imported (executes model output as code)",
                        location=f"{rel(root, f)}:{lineno}",
                        message=(
                            "A LangChain chain class that executes the model's output as code "
                            "or shell commands is imported (LLMBashChain, PALChain, or "
                            "LLMMathChain). These classes live in langchain_experimental "
                            "because they are inherently unsafe — there is no sandboxing, "
                            "no execution timeout, and no output schema validation. A "
                            "successful prompt injection attack on the feeding LLM becomes "
                            "arbitrary code execution on the host."
                        ),
                        remediation=(
                            "Replace with a scoped tool that validates the model's output "
                            "before execution: parse the response into a structured schema "
                            "(Pydantic model or JSON schema), validate each field, and "
                            "execute only pre-approved operations via an allowlist. If shell "
                            "execution is required, use a dedicated sandbox (Docker container "
                            "without network or filesystem access, E2B ephemeral sandbox, "
                            "or AWS Lambda with restricted IAM role) and suppress with "
                            "`# security: allow-langchain-unsafe-chain`."
                        ),
                        rule="langchain-unsafe-chain/dangerous-chain-imported",
                        standards=list(_STANDARDS),
                    )]
        return []

    def _check_allow_dangerous_code(
        self, root: Path, files: list[tuple[Path, str]]
    ) -> list[Finding]:
        for f, text in files:
            for lineno, line in enumerate(text.splitlines(), 1):
                if _ALLOW_DANGEROUS_CODE.search(line):
                    return [Finding(
                        check_id=self.id,
                        severity="high",
                        title="LangChain dangerous code execution explicitly enabled (allow_dangerous_code=True)",
                        location=f"{rel(root, f)}:{lineno}",
                        message=(
                            "`allow_dangerous_code=True` is set. LangChain requires this flag "
                            "as an explicit safety acknowledgement when using chain types that "
                            "execute model output as code (PALChain, LLMMathChain). Setting "
                            "it confirms the execution path is active. A prompt injection "
                            "attack on the LLM feeding this chain results in code execution "
                            "on the host process."
                        ),
                        remediation=(
                            "Remove the dangerous chain and the flag. Implement the "
                            "same functionality via structured output: prompt the model to "
                            "return a JSON object with the computed value, then parse and "
                            "validate it. If the execution cannot be eliminated, move it to "
                            "a sandboxed environment and suppress with "
                            "`# security: allow-langchain-unsafe-chain`."
                        ),
                        rule="langchain-unsafe-chain/allow-dangerous-code",
                        standards=list(_STANDARDS),
                    )]
        return []
