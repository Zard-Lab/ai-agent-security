"""Exclude advisor — suggest (never apply) directories a repo may want to demote or exclude.

agentsec keeps its *global* non-product lists deliberately tiny (universal conventions only — see
`detect.NONPRODUCT_DIR_ALT`). Everything repo-specific (`evals/`, offline `scripts/`, generated
dumps, vendored trees) is opt-in per repo. This module is the **discovery layer** that bridges the
gap: it scores each directory by how likely it is non-product and proposes the strong candidates,
annotated with *why*, for the user to opt into `.agentsec/config.json` (via `config.write_repo_config`).

**Robustness via corroboration, not names.** A directory is suggested only when signals from **≥2
independent axes** agree, including **≥1 robust axis** (import-unreachability, structural shape, or
already-excluded). A name match alone never suggests — so a repo that genuinely *serves* an `evals/`
endpoint (import-reachable, real route files, not gitignored) is never proposed.

Each candidate is classified **demote** (still scanned, ranked low — tests/eval/script source where a
real bug must stay visible) or **exclude** (hard drop — vendored/generated/dead code). The advisor is
advisory only: it returns `Candidate`s; persisting them is a separate, consent-gated step (the CLI).

The hardwired Layer-1 trees (`tests/`, `fixtures/`, `migrations/`, ...) are never *proactive*
candidates (already rank-demoted by convention), but Layer 1 never DROPS an external scanner's
findings, so a noisy tests tree still counts toward report totals. The reactive half therefore
proposes archiving such a tree once a completed audit proves it holds an all-low/info cluster,
and the CLI discloses the trees on proactive runs (#716).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from agentsec.config import _DEFAULT_NONPRODUCT_PATHS
from agentsec.detect import ARCHIVE_SEGMENTS, StackProfile
from agentsec.findings import Finding
from agentsec.guards.base import is_nonproduct_path
from agentsec.reachability import unreachable_dirs
from agentsec.walk import GitignoreMatcher, walk_files

# Directory-name hints (weak on their own — a name only nudges, never decides).
_NAME_HINTS = (
    ARCHIVE_SEGMENTS
    | _DEFAULT_NONPRODUCT_PATHS
    | {
        "test", "tests", "__tests__", "__mocks__", "mocks", "fixture", "fixtures",
        "example", "examples", "sample", "samples", "e2e", "spec", "specs", "stories",
        ".storybook", "sandbox", "playground", "demo", "demos", "notebook", "notebooks",
        "bench", "benchmark", "benchmarks", "script", "tooling", "doc", "eval", "judge",
        "cypress",
    }
)
# Names that classify a candidate as a HARD-exclude (drop) rather than demote.
_EXCLUDE_NAMES = ARCHIVE_SEGMENTS | {"vendor", "vendored", "third_party", "dist", "build", "out", "target"}

# Files whose mere shape marks a directory as non-product (test/notebook/story tooling).
_NONPRODUCT_FILE_RE = re.compile(
    r"(?:^test_.*\.py$|.*_test\.py$|^conftest\.py$|^__main__\.py$"
    r"|.*\.(?:test|spec|stories)\.[a-z0-9]+$)",
    re.IGNORECASE,
)
# Headers that mark a generated/vendored artifact (read from the file's first lines).
_GENERATED_HEADER_RE = re.compile(
    r"DO NOT EDIT|@generated|autogenerated|auto-generated|generated by|pg_dump|supabase db dump",
    re.IGNORECASE,
)
_GENERATED_SNIFF_LINES = 25


@dataclass
class Candidate:
    """One suggested directory, with the evidence behind the suggestion."""

    directory: str                         # repo-relative, forward-slash
    kind: str                              # "demote" | "exclude"
    confidence: str                        # "high" | "heuristic"
    signals: list[str] = field(default_factory=list)   # human-readable "why" lines
    finding_count: int = 0                 # findings currently under this dir (reactive)
    severity_mix: dict[str, int] = field(default_factory=dict)


def _matcher(root: Path, name: str) -> GitignoreMatcher | None:
    """A `.gitignore`/`.dockerignore` matcher for the repo root (both share the syntax)."""
    p = root / name
    if not p.is_file():
        return None
    try:
        return GitignoreMatcher.from_text(p.read_text(encoding="utf-8", errors="ignore"))
    except OSError:
        return None


def _is_generated(members: list[Path]) -> bool:
    for f in members:
        try:
            with f.open(encoding="utf-8", errors="ignore") as fh:
                head = "".join(next(fh, "") for _ in range(_GENERATED_SNIFF_LINES))
        except OSError:
            continue
        if _GENERATED_HEADER_RE.search(head):
            return True
    return False


def _dir_members(root: Path) -> dict[str, list[Path]]:
    """Map every repo-relative directory (that holds files) to its immediate file members.

    Walks **past `.gitignore`** (`respect_gitignore=False`) so gitignored dirs are still visible —
    being gitignored is itself a non-product signal, and the advisor must be able to surface them.
    Vendored/build dirs and nested worktrees (`walk.DEFAULT_EXCLUDE_DIRS`) are still skipped."""
    by_dir: dict[str, list[Path]] = {}
    for f in walk_files(root, respect_gitignore=False):
        rel = f.relative_to(root).parent.as_posix()
        if rel in (".", ""):
            continue
        by_dir.setdefault(rel, []).append(f)
    return by_dir


def _score_dir(
    reldir: str,
    members: list[Path],
    unreachable: set[str],
    gitignore: GitignoreMatcher | None,
    dockerignore: GitignoreMatcher | None,
) -> Candidate | None:
    """Apply the corroboration rule to one directory. Returns a Candidate or None (not suggested)."""
    seg = reldir.rsplit("/", 1)[-1].lower()
    signals: list[str] = []

    # --- robust axes ---
    robust = 0
    if reldir in unreachable:
        robust += 1
        signals.append("not imported by any served entrypoint (import-unreachable)")
    n_np = sum(1 for m in members if _NONPRODUCT_FILE_RE.match(m.name) or m.suffix == ".ipynb")
    structural = bool(members) and n_np * 2 >= len(members) and n_np > 0
    if structural:
        robust += 1
        signals.append(f"{n_np}/{len(members)} files are test/notebook/story shape")
    excluded = bool(
        (gitignore and gitignore.match(reldir, is_dir=True))
        or (dockerignore and dockerignore.match(reldir, is_dir=True))
    )
    if excluded:
        robust += 1
        signals.append("already ignored by .gitignore/.dockerignore")

    # --- weak axes ---
    weak = 0
    if seg in _NAME_HINTS or seg in _EXCLUDE_NAMES:
        weak += 1
        signals.append(f"directory name '{seg}' is a common non-product convention")
    generated = _is_generated(members)
    if generated:
        weak += 1
        signals.append("contains a generated/vendored file header (DO NOT EDIT / pg_dump / @generated)")

    # Corroboration: suggest only with >=2 axes total AND >=1 robust axis. Name/header alone never suggests.
    if robust == 0 or (robust + weak) < 2:
        return None

    kind = "exclude" if (generated or seg in _EXCLUDE_NAMES) else "demote"
    confidence = "high" if (excluded or generated or seg in _EXCLUDE_NAMES or robust >= 2) else "heuristic"
    return Candidate(directory=reldir, kind=kind, confidence=confidence, signals=signals)


def suggest_proactive(root: Path, profile: StackProfile) -> list[Candidate]:
    """Walk-based suggestions (no scan needed). The proactive half of the advisor."""
    from agentsec.config import load_repo_config

    cfg = load_repo_config(root)
    already = cfg.archive_segments | cfg.nonproduct_segments  # don't re-suggest opted-in trees
    unreachable = unreachable_dirs(root, profile)
    gitignore = _matcher(root, ".gitignore")
    dockerignore = _matcher(root, ".dockerignore")
    out: list[Candidate] = []
    for reldir, members in sorted(_dir_members(root).items()):
        # Skip dirs already covered, so suggesting them is just noise: (a) anything under a tree the
        # repo already opted into config (segment match, so a nested `old/x/tools` is skipped too), and
        # (b) the hardwired Layer-1 conventions (tests/fixtures/migrations/…). The advisor's value is
        # the dirs NOT already covered (evals/, scripts/, repo-specific trees). NOTE: (b) is only
        # "covered" for guards; external-scanner findings under a Layer-1 tree are rank-demoted, never
        # dropped, so `_builtin_tree_candidates` (reactive) proposes archiving such a tree when a scan
        # proves it noisy, and the CLI discloses these trees on proactive runs (#716).
        if (set(reldir.lower().split("/")) & already) or is_nonproduct_path(reldir + "/_"):
            continue
        cand = _score_dir(reldir, members, unreachable, gitignore, dockerignore)
        if cand is not None:
            out.append(cand)
    return _dedupe_nested(out)


def builtin_demoted_roots(root: Path) -> list[str]:
    """Top-most directories covered by the hardwired Layer-1 conventions (`tests/`, `fixtures/`,
    `migrations/`, ...): exactly the trees `suggest_proactive` deliberately never suggests. Exposed
    so the CLI can DISCLOSE them instead of silently omitting them: Layer 1 only rank-demotes
    external-scanner findings (the DROP half is per-guard), so these trees still count toward the
    report totals (#716)."""
    roots: set[str] = set()
    for reldir in _dir_members(root):
        parts = reldir.split("/")
        for i in range(1, len(parts) + 1):
            prefix = "/".join(parts[:i])
            if is_nonproduct_path(prefix + "/_"):
                roots.add(prefix)
                break
    return sorted(roots)


def _dedupe_nested(cands: list[Candidate]) -> list[Candidate]:
    """Drop a candidate whose parent dir is already a candidate of the same kind (suggest the top tree)."""
    by_dir = {c.directory: c for c in cands}
    out: list[Candidate] = []
    for c in cands:
        parts = c.directory.split("/")
        covered = any(
            "/".join(parts[:i]) in by_dir and by_dir["/".join(parts[:i])].kind == c.kind
            for i in range(1, len(parts))
        )
        if not covered:
            out.append(c)
    return out


# --- reactive overlay: layer real scan output onto the proactive candidates -------------------


def _location_dir(location: str) -> str:
    """The repo-relative directory of a finding location (`a/b/x.py:9` -> `a/b`)."""
    path = (location or "").replace("\\", "/").split(":", 1)[0]
    return path.rsplit("/", 1)[0] if "/" in path else ""


def _under(candidate_dir: str, location: str) -> bool:
    d = _location_dir(location)
    return d == candidate_dir or d.startswith(candidate_dir + "/")


# Checks whose findings are secret-detection hits: never advise archiving over one, whatever its
# severity (an archive is a hard DROP, and a committed secret in a tests tree is still a leak).
# Today this veto is redundant defense-in-depth: the gitleaks runner emits severity="high" for
# everything, so the medium+ gate above already blocks it. Kept deliberately, so the guarantee
# survives if that severity model ever changes (#724 review).
_SECRET_CHECK_IDS = frozenset({"gitleaks"})


def _builtin_tree_candidates(root: Path, findings: list[Finding]) -> list[Candidate]:
    """Archive proposals for the hardwired Layer-1 trees, driven by scan evidence only (#716).

    `suggest_proactive` skips these trees ("already covered"), which is true for guards but not for
    external scanners: their findings are rank-demoted, never dropped, so a tests tree can dominate
    the report totals while staying invisible to the advisor (851 of 866 noise-floor findings on the
    reference RAG-app run). A demote proposal would be a no-op (the rank-demote already applies), so the only
    meaningful proposal is `exclude` (`archive_paths`), gated conservatively: never for a clean tree,
    never over a medium+ finding (stricter than the product-reachable veto: an archive drops
    EVERYTHING under the tree), and never over a secret-detection hit."""
    from agentsec.config import load_repo_config

    cfg = load_repo_config(root)
    # Skip only ARCHIVED trees (their findings are already dropped). A Layer-1 tree in
    # `nonproduct_paths` is deliberately still proposed: that config entry is a no-op for it (the
    # rank-demote already applies by convention, and the counts never consult the demote stamp),
    # and it is the natural-but-ineffective hand-fix the #716 reporter applied. Skipping on it
    # would recreate the exact silent dead end this function exists to close (#724 review).
    already = cfg.archive_segments
    total_low = sum(1 for f in findings if f.severity in ("low", "info"))
    out: list[Candidate] = []
    for reldir in builtin_demoted_roots(root):
        if set(reldir.lower().split("/")) & already:
            continue
        under = [f for f in findings if _under(reldir, f.location)]
        if not under:
            continue  # a clean built-in tree is never suggested (the original design intent, kept)
        if any(f.severity not in ("low", "info") for f in under):
            continue  # a medium+ finding here: surface it, never suggest dropping the tree
        if any(f.check_id in _SECRET_CHECK_IDS for f in under):
            continue
        mix: dict[str, int] = {}
        for f in under:
            mix[f.severity] = mix.get(f.severity, 0) + 1
        share = round(100 * len(under) / total_low) if total_low else 0
        out.append(Candidate(
            directory=reldir,
            kind="exclude",
            # High confidence only when the tree is the report's dominant low-severity source.
            confidence="high" if 2 * len(under) >= total_low else "heuristic",
            signals=[
                "already rank-demoted by the built-in conventions, but scanner findings here still "
                "count toward report totals",
                f"{len(under)} finding(s) here, all low/info ({share}% of the report's "
                f"{total_low} low-severity finding(s))",
                "archive_paths is a hard DROP: future findings under this tree (secrets included) "
                "would no longer be reported",
            ],
            finding_count=len(under),
            severity_mix=mix,
        ))
    return out


def suggest(root: Path, profile: StackProfile, findings: list[Finding] | None = None) -> list[Candidate]:
    """The advisor entrypoint. Proactive walk-based candidates, plus — when `findings` from a completed
    audit are supplied — a reactive overlay that fills each candidate's finding stats, **vetoes** any
    candidate that holds a real high-severity *product* finding (Sonar conservatism: never suggest
    sweeping a serious bug under the rug), and boosts confidence when the dir's findings are an
    all-low-priority, few-guard cluster (a measured non-product signature, not a guessed name).
    The hardwired Layer-1 trees, which the proactive half never suggests, are appended here as
    archive candidates when the scan shows an all-low/info cluster under them (#716)."""
    cands = suggest_proactive(root, profile)
    if not findings:
        return cands

    # Lazy import: `prioritize` imports `findings`, which would otherwise risk an import cycle.
    from agentsec.prioritize import reachability

    out: list[Candidate] = []
    for c in cands:
        under = [f for f in findings if _under(c.directory, f.location)]
        # Veto: a serious bug in still-product-reachable code here — surface it, don't suggest hiding it.
        if any(f.severity in ("critical", "high") and reachability(f) == "product" for f in under):
            continue
        c.finding_count = len(under)
        mix: dict[str, int] = {}
        for f in under:
            mix[f.severity] = mix.get(f.severity, 0) + 1
        c.severity_mix = mix
        if under:
            low = sum(1 for f in under if f.severity in ("low", "info"))
            guards = {f.check_id for f in under}
            c.signals.append(
                f"{len(under)} finding(s) here from {len(guards)} guard(s), {low} low-severity"
            )
            if c.confidence != "high" and low == len(under) and len(guards) <= 2:
                c.confidence = "high"  # measured: an all-low-severity, few-guard cluster
        out.append(c)
    out.extend(_builtin_tree_candidates(root, findings))
    return out
