# --- declared check metadata ------------------------------------------------
# Built eagerly at import: every check is already instantiated above, so there is nothing to
# invalidate and no cache to clear. Deliberately NOT an `lru_cache` over a lazy walk — a cached
# lazy index would keep answering from a stale snapshot after a test monkeypatches `ALL_GUARDS`,
# which is the kind of wrong-but-green answer CLAUDE.md Rule 3 exists to catch.
# `test_check_meta_index_covers_every_registered_check` asserts nothing was silently dropped by
# the dict comprehension (a duplicate id would collide, keeping only the last).
# Every registered check, guards and runners alike, seen only through what they declare. The
# explicit `CheckMeta` element type is load-bearing: `Guard` and `Runner` share no ancestor, so
# without it both type-checkers unify the tuple to `object` and stop verifying that either class
# actually satisfies the protocol.
ALL_CHECKS: tuple[CheckMeta, ...] = (*ALL_GUARDS, *ALL_RUNNERS)

_CHECK_META: dict[str, CheckMeta] = {c.id: c for c in ALL_CHECKS}


def check_meta(check_id: str) -> CheckMeta | None:
    """The declared reporting metadata for a registered check id.

    `None` for an id produced outside the registry — an ingested or synthetic finding
    (`zap`, `gitignore-cap`, `sarif:<tool>`) has no class to declare anything on, so callers
    must handle it rather than assume every `check_id` resolves.
    """
    return _CHECK_META.get(check_id)


# --- security tiers ---------------------------------------------------------
# The "baseline" floor: universal hygiene that applies to essentially any app,
# independent of its stack (always-on or gated only on python/frontend code).
# Everything else is "stack" — gated on a specific capability (payments, supabase,
# llm, fastapi-routes, sql). The baseline is what a brand-new, undetected app gets
# *before* and *regardless of* stack detection: ship-secure-by-default.
#
# DRAINED (BB4). A guard declares `tier = "baseline"` on its own class instead. Kept rather than
# deleted because `is_baseline_guard()` still unions it in: an id re-added here therefore still
# TAKES EFFECT, so `test_baseline_ids_legacy_stays_drained` is the single thing that catches the
# re-add. Drop the union and a stray id here becomes a silent no-op instead — a change that reads
# as working and does nothing.
# NOTE: unlike the frozenset, a class attribute cannot hold a FORWARD REFERENCE to a held-but-
# unmerged guard (there is no class yet to declare it on). Zero such references existed when this
# was drained; see `tests/test_tiers.py`.
BASELINE_GUARD_IDS: frozenset[str] = frozenset()


def is_baseline_guard(check_id: str) -> bool:
    """True if `check_id` is part of the universal baseline floor (vs the stack overlay)."""
    meta = _CHECK_META.get(check_id)
    if meta is not None:
        return meta.tier == "baseline"
    return check_id in BASELINE_GUARD_IDS
